"""Deterministic JD analysis and honest coverage scoring.

WHY THIS MODULE EXISTS
----------------------
The number this repo printed next to a tailored résumé used to be an LLM's
guess, re-rolled on every run, and it was labelled an "ATS match score". Both
halves of that were wrong.

No major ATS computes a résumé match percentage. Taleo's familiar "75%" scores
the *questionnaire answers* a candidate types into the application form, not the
résumé. Workday emits an A/B/C/D band from recruiter-configured filters.
Greenhouse emits nothing at all and offers only unstemmed Boolean search. So a
percentage presented as "what the ATS will score you" is fiction however it is
computed. What CAN be computed honestly is how much of *this job description*
the résumé actually covers, and that is what this module produces. Every
user-facing string calls it **JD coverage**; the internal dict keys (`overall`,
`ats_score`) survive only because server/dashboard.py and index.html read them.

Three measurement decisions follow from the retrieval literature and from what
the lexical layer of a real ATS can actually do:

* **Presence, not frequency.** BM25's ``k1`` saturates term repetition; the
  term-frequency contribution here is hard-capped at three occurrences
  (``log1p(min(count, 3))``) and each JD term adds its weight to the covered
  total exactly once. Repetition past ``max_repetition`` is a *deduction* —
  keyword stuffing is the one place frequency moves the number, and it only
  ever moves it down.
* **Phrases are contiguous or they are nothing.** Greenhouse Boolean has no
  stemming and no phrase inference: ``"machine learning"`` is a quoted-phrase
  hit or two unrelated words. Multi-word terms must therefore match inside a
  *single line* of the résumé; a term whose words straddle a line break lands in
  ``phrase_breaks`` and is NOT counted as covered.
* **Titles compare more literally than skills.** Résumé parsers (Affinda's
  default configuration is the documented case) normalise skills against a
  taxonomy but leave job titles alone. Skills therefore get alias/acronym
  expansion here and titles get none — ``title_alignment`` is raw token overlap.

Aliasing has a direction, and conflating the two directions is fabrication.
``llm`` and ``large language model`` are one referent, so membership in a
symmetric group runs both ways. ``mysql`` truthfully entails ``sql``, but
``sql`` does not entail ``mysql`` — encoding that pair symmetrically would let a
résumé claim PostgreSQL on the strength of MySQL. Symmetric groups live in
``ALIAS_TABLE``, one-way entailments in ``TERM_IMPLIES``; both are hand-curated
and neither is ever generated by a model.

Everything here is pure and deterministic: same input, same output, always. The
only I/O is a cached read of ``config/base_resume.yaml``, and the single
optional LLM call (``_llm_requirement_seed``) fires only for a title-only
posting, produces only a *seed list of candidate terms*, and every one of those
terms is then re-verified by the same deterministic shape gate as any other.

Out of scope permanently: hidden text, white-on-white text, off-page keyword
blocks, or any other content a human reader of the document cannot see. Nothing
in this module produces or recommends such content.
"""

