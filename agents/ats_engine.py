@dataclass
class EntryScore:
    key: str                             # "W1".."W6" / "P1".."P6", base-résumé order
    entry: dict                          # the base résumé entry, unmodified
    kind: str                            # "work_experience" | "project_experience"
    raw: float
    keyword_hits: dict[str, float] = field(default_factory=dict)
    requirement_hits: dict[str, float] = field(default_factory=dict)
    bullet_scores: list[float] = field(default_factory=list)
    bullet_keyword_hits: list[dict[str, float]] = field(default_factory=list)
    bullet_requirement_hits: list[dict[str, float]] = field(default_factory=list)


def _hit(term: str, haystack_norm: str) -> bool:
    return any(contains_phrase(haystack_norm, f) for f in _attesting_sources(term))


def score_entry(entry: dict, kind: str, key: str, analysis: JDAnalysis, *,
                recency_rank: int | None = None) -> EntryScore:
    """Score one base-résumé entry against a JD analysis.

    ``recency_rank`` is supplied by :func:`score_entries` rather than derived
    here: whether an entry is the most recent is a property of the set, not of
    the entry, and a function that silently re-read the whole résumé to find out
    would no longer be pure.
    """
    entry = entry or {}
    bullets = [_bullet_text(b) for b in (entry.get("bullets") or [])]
    stack = (entry.get("tech_stack") or entry.get("stack")
             or entry.get("organization") or entry.get("company") or "")
    entry_hay = normalize(" ".join([str(entry.get("title") or ""), str(stack),
                                    " ".join(bullets)]))

    keyword_hits = {kw.term: kw.weight for kw in analysis.keywords
                    if _hit(kw.term, entry_hay)}
    requirement_hits: dict[str, float] = {}
    for req in analysis.requirements:
        if not req.terms:
            continue
        need = max(1, math.ceil(0.5 * len(req.terms)))
        if sum(1 for t in req.terms if _hit(t, entry_hay)) >= need:
            requirement_hits[req.id] = req.weight

    raw = sum(keyword_hits.values()) + 1.5 * sum(requirement_hits.values())
    if kind == "work_experience" and recency_rank is not None:
        raw *= 1.10 if recency_rank == 0 else 1.05 if recency_rank == 1 else 1.0

    weights = [kw.weight for kw in analysis.keywords]
    mean_kw = (sum(weights) / len(weights)) if weights else 0.0

    b_scores: list[float] = []
    b_kw: list[dict[str, float]] = []
    b_req: list[dict[str, float]] = []
    for b in bullets:
        hay = normalize(b)
        khits = {kw.term: kw.weight for kw in analysis.keywords if _hit(kw.term, hay)}
        rhits = {req.id: req.weight for req in analysis.requirements
                 if req.terms and any(_hit(t, hay) for t in req.terms)}
        score = sum(khits.values()) + 1.5 * sum(rhits.values())
        if QUANT_RE.search(b):
            score += 0.30 * mean_kw
        b_scores.append(round(score, 6))
        b_kw.append(khits)
        b_req.append(rhits)

    return EntryScore(key=key, entry=entry, kind=kind, raw=round(raw, 6),
                      keyword_hits=keyword_hits, requirement_hits=requirement_hits,
                      bullet_scores=b_scores, bullet_keyword_hits=b_kw,
                      bullet_requirement_hits=b_req)


def score_entries(entries: Sequence[dict], kind: str, analysis: JDAnalysis, *,
                  prefix: str | None = None) -> list[EntryScore]:
    """Score a whole section, applying the recency multiplier across the set."""
    prefix = prefix or ("W" if kind == "work_experience" else "P")
    ranks: dict[int, int] = {}
    if kind == "work_experience":
        years = []
        for i, e in enumerate(entries):
            found = _YEAR_RE.findall(str((e or {}).get("dates", "")))
            years.append((int(found[-1]) if found else -1, -i, i))
        for rank, (_y, _neg, idx) in enumerate(sorted(years, reverse=True)):
            ranks[idx] = rank
    return [score_entry(e, kind, f"{prefix}{i + 1}", analysis, recency_rank=ranks.get(i))
            for i, e in enumerate(entries)]


def select_entries(scores: list[EntryScore], k: int) -> list[EntryScore]:
    """Greedy marginal-coverage selection (submodular set cover).

    This is the layer that makes selection JD-dependent. Ranking by raw score
    alone produced 9 distinct entry selections across 197 shipped résumés,
    because the strongest entries score highly against *every* JD; greedy
    marginal gain instead rewards an entry for what nothing already selected
    covers. Ties break on ``(-gain, -raw, base-résumé index)``, so the result is
    fully deterministic, and an entry with ``raw == 0`` is still eligible — an
    empty EXPERIENCE section is worse than a weak one.
    """
    remaining = list(enumerate(scores))
    selected: list[EntryScore] = []
    covered_kw: set[str] = set()
    covered_req: set[str] = set()

    while len(selected) < k and remaining:
        best_key: tuple[float, float, int] | None = None
        best_pos = 0
        for pos, (idx, c) in enumerate(remaining):
            gain = (sum(w for t, w in c.keyword_hits.items() if t not in covered_kw)
                    + 1.5 * sum(w for r, w in c.requirement_hits.items()
                                if r not in covered_req)
                    + 0.15 * c.raw)
            key = (-round(gain, 6), -c.raw, idx)
            if best_key is None or key < best_key:
                best_key, best_pos = key, pos
        _idx, chosen = remaining.pop(best_pos)
        selected.append(chosen)
        covered_kw |= set(chosen.keyword_hits)
        covered_req |= set(chosen.requirement_hits)
    return selected


def select_bullets(es: EntryScore, k: int, *, min_k: int = 1) -> list[int]:
    """Indices of the best `k` base bullets, returned in original résumé order.

    Same marginal-coverage greedy as :func:`select_entries`, so two bullets
    proving the same requirement do not both get picked while a third
    requirement goes unproved. Returns at least ``min_k`` indices even when
    every score is zero. Indices come back ascending rather than
    best-first because the caller renders them in résumé reading order.
    """
    n = len(es.bullet_scores)
    if n == 0:
        return []
    want = max(min_k, min(k, n))
    remaining = list(range(n))
    picked: list[int] = []
    covered_kw: set[str] = set()
    covered_req: set[str] = set()

    def khits(i: int) -> dict[str, float]:
        return es.bullet_keyword_hits[i] if i < len(es.bullet_keyword_hits) else {}

    def rhits(i: int) -> dict[str, float]:
        return es.bullet_requirement_hits[i] if i < len(es.bullet_requirement_hits) else {}

    while len(picked) < want and remaining:
        best_key: tuple[float, float, int] | None = None
        best_pos = 0
        for pos, i in enumerate(remaining):
            gain = (sum(w for t, w in khits(i).items() if t not in covered_kw)
                    + 1.5 * sum(w for r, w in rhits(i).items() if r not in covered_req)
                    + 0.15 * es.bullet_scores[i])
            key = (-round(gain, 6), -es.bullet_scores[i], i)
            if best_key is None or key < best_key:
                best_key, best_pos = key, pos
        i = remaining.pop(best_pos)
        picked.append(i)
        covered_kw |= set(khits(i))
        covered_req |= set(rhits(i))
    return sorted(picked)


def _unique_contribution(es: EntryScore, others: Sequence[EntryScore]) -> float:
    kw: set[str] = set()
    rq: set[str] = set()
    for o in others:
        kw |= set(o.keyword_hits)
        rq |= set(o.requirement_hits)
    return (sum(w for t, w in es.keyword_hits.items() if t not in kw)
            + 1.5 * sum(w for r, w in es.requirement_hits.items() if r not in rq))


def swap_weakest(selected: list[EntryScore], pool: list[EntryScore],
                 analysis: JDAnalysis) -> list[EntryScore] | None:
    """Drop the least marginally useful selected entry and re-select without it.

    The iterate loop's re-selection primitive. Returns None when the pool offers
    nothing new, so the caller stops rather than spinning on the same set.
    """
    if not selected:
        return None
    weakest_pos = min(
        range(len(selected)),
        key=lambda i: (round(_unique_contribution(
            selected[i], selected[:i] + selected[i + 1:]), 6), selected[i].raw, -i))
    weakest = selected[weakest_pos]

    chosen_keys = {s.key for s in selected}
    fresh = [p for p in pool if p.key != weakest.key and p.key not in chosen_keys]
    if not fresh:
        return None
    candidates = [s for s in selected if s.key != weakest.key] + fresh
    return select_entries(candidates, len(selected))


