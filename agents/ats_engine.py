def _as_sections(jd_or_sections: Any) -> dict[str, str]:
    if isinstance(jd_or_sections, dict):
        return {str(k): str(v or "") for k, v in jd_or_sections.items()}
    return split_jd_sections(str(jd_or_sections or ""))


def _accept_gram(gram: str, n: int, section_hay: str, lexicon: frozenset[str],
                 original: str) -> bool:
    if gram in BOILERPLATE_PHRASES or any(bp in gram for bp in BOILERPLATE_PHRASES):
        return False
    if not contains_phrase(section_hay, gram):
        # An artefact of the hyphen expansion in tokens(): it never occurred
        # contiguously in the posting, so it is not a term the posting used.
        return False
    if gram in lexicon or _flatten(gram) in lexicon:
        return True
    if len(gram) < 2 or not any(c.isalpha() for c in gram):
        return False
    parts = gram.split()
    if n == 1 and (gram in LOW_SIGNAL or gram in STOPWORDS):
        # The capitalisation route must not rescue "Experience" just because a
        # sentence began with it. This is the rule that stops generic HR
        # vocabulary from dominating the keyword list.
        return False
    if n >= 3 and any(t in STOPWORDS for t in parts[1:-1]):
        # "combination of operations", "always to produce": sentence glue that
        # happens to start and end on content words. A real multi-word term
        # almost never carries a stopword in the middle.
        return False
    if SKILLISH_RE.search(gram):
        return True
    if _is_capitalised_in(gram, original):
        return True
    if n >= 2 and parts[0] not in LOW_SIGNAL and parts[-1] not in LOW_SIGNAL:
        return True
    return False


def extract_keywords(jd_or_sections: Any, *, top_n: int = MAX_KEYWORDS,
                     seed_terms: Sequence[str] = (),
                     base_resume_path: str | Path | None = None) -> list[Keyword]:
    """Weighted JD terms — presence-scored, phrase-preserving, deterministic.

    Frequency saturates at three occurrences (BM25's ``k1`` analogue), phrases
    outrank their own unigrams (``_LEN_BONUS``) and then absorb them (subsumption
    pruning), and generic HR vocabulary is either rejected outright or discounted
    to ``IDF_PRIOR_LOW``. ``seed_terms`` — the ranker's LLM keywords — stay
    advisory: a seed absent from the posting enters at half the median weight
    and is marked ``section="unknown"``, so a hallucinated seed can never outrank
    a term the JD actually used.
    """
    sections = _as_sections(jd_or_sections)
    lexicon = tech_lexicon(base_resume_path)
    original = "\n".join(sections.values())

    # n-grams come from one LINE at a time, never across two. A posting's line
    # breaks are where its phrases end, so a gram spanning two bullets
    # ("services build machine") is an artefact of concatenation naming a term
    # no résumé could legitimately contain. Occurrence counts are summed the
    # same way, for the same reason.
    line_hays: list[str] = []
    accepted: dict[str, dict[str, Any]] = {}
    for section, text in sections.items():
        if not text:
            continue
        ws = SECTION_WEIGHTS.get(section, SECTION_WEIGHTS["unknown"])
        for line in text.splitlines():
            line_hay = normalize(line)
            if not line_hay:
                continue
            line_hays.append(line_hay)
            for gram, _idx in ngrams(tokens(line), 3):
                rec = accepted.get(gram)
                if rec is not None:
                    if ws > rec["ws"]:
                        rec["ws"] = ws
                        rec["section"] = section
                    continue
                n = gram.count(" ") + 1
                if not _accept_gram(gram, n, line_hay, lexicon, original):
                    continue
                accepted[gram] = {"ws": ws, "section": section, "n": n}

    keywords: dict[str, Keyword] = {}
    first_at: dict[str, int] = {}
    for gram, rec in accepted.items():
        count = sum(_count_phrase(h, gram) for h in line_hays)
        if count <= 0:
            continue
        parts = gram.split()
        idf = IDF_PRIOR_LOW if all(p in LOW_SIGNAL for p in parts) else IDF_PRIOR_DEFAULT
        tf = math.log1p(min(count, 3))
        weight = rec["ws"] * tf * idf * _LEN_BONUS[rec["n"]]
        match = _term_regex(gram).search(original)
        first_at[gram] = match.start() if match else len(original)
        keywords[gram] = Keyword(
            term=gram,
            display=match.group(0) if match else gram,
            weight=round(weight, 6),
            count=count,
            section=rec["section"],
            n=rec["n"],
            is_technical=bool(gram in lexicon or _flatten(gram) in lexicon
                              or SKILLISH_RE.search(gram)),
        )

    keywords = _prune_subsumed(keywords, lexicon)
    keywords = _merge_seeds(keywords, seed_terms, lexicon, original)

    # Weight ties are common in a short or heading-free posting, where every
    # gram shares one section weight and a count of 1. Breaking those ties
    # alphabetically floods the list with prose starting in "a"; breaking them
    # on domain-recognisability and then on position in the document keeps the
    # posting's own emphasis and stays fully deterministic.
    return sorted(keywords.values(),
                  key=lambda k: (-k.weight, not k.is_technical,
                                 first_at.get(k.term, len(original)), k.term))[:top_n]


def _prune_subsumed(keywords: dict[str, Keyword],
                    lexicon: frozenset[str]) -> dict[str, Keyword]:
    """Drop a unigram that a stronger containing phrase already carries.

    With "machine learning" present, a separate "learning" entry double-counts
    the same evidence. A term the base résumé names literally is never dropped:
    that is a surface form an unstemmed ATS search may look for on its own.
    """
    drop: set[str] = set()
    for phrase in [k for k in keywords.values() if k.n >= 2]:
        for part in phrase.term.split():
            uni = keywords.get(part)
            if uni is None or part in lexicon:
                continue
            if phrase.weight >= 0.8 * uni.weight and phrase.count >= 0.6 * uni.count:
                drop.add(part)
    return {t: k for t, k in keywords.items() if t not in drop}


def _merge_seeds(keywords: dict[str, Keyword], seed_terms: Sequence[str],
                 lexicon: frozenset[str], original: str) -> dict[str, Keyword]:
    seeds = [normalize(s) for s in (seed_terms or [])]
    seeds = [s for s in seeds if s and len(s.split()) <= 3]
    if not seeds:
        return keywords

    computed = sorted(k.weight for k in keywords.values())
    if computed:
        mid = len(computed) // 2
        median = (computed[mid] if len(computed) % 2
                  else (computed[mid - 1] + computed[mid]) / 2.0)
    else:
        median = SECTION_WEIGHTS["unknown"]
    seed_weight = round(0.5 * median, 6)

    out = dict(keywords)
    for s in seeds:
        if s in out:                     # already earned its weight from the JD text
            continue
        if any(bp in s for bp in BOILERPLATE_PHRASES):
            continue
        out[s] = Keyword(
            term=s,
            display=_first_occurrence(s, original) or s,
            weight=seed_weight,
            count=0,
            section="unknown",
            n=min(3, s.count(" ") + 1),
            is_technical=bool(s in lexicon or _flatten(s) in lexicon
                              or SKILLISH_RE.search(s)),
        )
    return out


