def _bullet_text(b: Any) -> str:
    if isinstance(b, dict):
        return str(b.get("text") or b.get("bullet") or "")
    return str(b or "")


def _build_zones(resume_data: Any) -> _Zones:
    z = _Zones()
    if resume_data is None:
        return z
    if isinstance(resume_data, str):
        # Text-only fallback for the optimizer's legacy positional call. Every
        # line becomes a bullet, which is the conservative reading: bullet
        # context is the strictest zone, so nothing is scored more leniently
        # than it would be with structured data.
        for i, line in enumerate(resume_data.splitlines(), start=1):
            if line.strip():
                z.bullets.append((f"bullet:line{i}", line.strip()))
        return z
    if not isinstance(resume_data, dict):
        return z

    for keys, prefix in ((("work_experience", "experience"), "W"),
                         (("project_experience", "projects"), "P")):
        entries: Any = []
        for k in keys:
            if resume_data.get(k):
                entries = resume_data[k]
                break
        if not isinstance(entries, (list, tuple)):
            continue
        for ei, entry in enumerate(entries, start=1):
            if not isinstance(entry, dict):
                continue
            key = f"{prefix}{ei}"
            for bi, b in enumerate(entry.get("bullets") or [], start=1):
                text = _bullet_text(b).strip()
                if text:
                    z.bullets.append((f"bullet:{key}.{bi}", text))
            for stack_key in ("tech_stack", "stack", "technologies"):
                if entry.get(stack_key):
                    z.skills.append((f"skills:{key} stack", str(entry[stack_key])))
            for hkey in ("title", "organization", "company", "location", "dates"):
                if entry.get(hkey):
                    z.header.append((f"header:{key}.{hkey}", str(entry[hkey])))

    skills = resume_data.get("skills") or resume_data.get("technical_skills") or {}
    if isinstance(skills, dict):
        for cat, val in skills.items():
            items = val if isinstance(val, str) else ", ".join(_split_items(val))
            z.skills.append((f"skills:{cat}", f"{cat}: {items}"))
    elif isinstance(skills, (list, tuple)):
        z.skills.append(("skills:all", ", ".join(str(s) for s in skills)))

    for edu in resume_data.get("education") or []:
        if isinstance(edu, dict):
            parts = [str(edu.get(k, "")) for k in
                     ("institution", "school", "degree", "location", "date", "graduation")]
            if edu.get("coursework"):
                parts.append(", ".join(_split_items(edu["coursework"])))
            z.header.append(("header:education", " ".join(p for p in parts if p)))
        elif edu:
            z.header.append(("header:education", str(edu)))

    for cert in resume_data.get("certifications") or []:
        name = cert.get("name") if isinstance(cert, dict) else cert
        if name:
            z.header.append(("header:certification", str(name)))

    return z


def _zone_lines(z: _Zones) -> dict[str, list[tuple[str, str]]]:
    return {"bullet": z.bullets, "skills": z.skills, "header": z.header}


def _locate(term: str, zones: _Zones) -> tuple[str | None, str | None]:
    """(zone, label) of the first line honestly covering `term`, else (None, None).

    Multi-word terms are matched per LINE, never against the concatenated
    document: words landing on two different lines are not a phrase hit to an
    unstemmed Boolean search, and counting them would inflate coverage exactly
    where it is least defensible.
    """
    forms = _attesting_sources(term)
    for zone, lines in _zone_lines(zones).items():
        for label, text in lines:
            hay = normalize(text)
            if any(contains_phrase(hay, f) for f in forms):
                return zone, label
    return None, None


def _spans_lines(term: str, zones: _Zones) -> bool:
    """True when a multi-word term appears only across a line boundary."""
    forms = _attesting_sources(term)
    joined = normalize(" \n ".join(t for _l, t in zones.bullets + zones.skills))
    return any(contains_phrase(joined, f) for f in forms)


def _parse_month_year(s: str) -> tuple[int, int] | None:
    low = normalize(s)
    if not low:
        return None
    year_m = _YEAR_RE.search(low)
    if not year_m:
        return None
    year = int(year_m.group(0))
    month = 1
    for name, num in _MONTHS.items():
        if re.search(rf"(?<![a-z]){name}", low):
            month = num
            break
    else:
        m = re.match(r"^(\d{1,2})[/-]\d{4}", low)
        if m and 1 <= int(m.group(1)) <= 12:
            month = int(m.group(1))
    return year, month


def _date_range(dates: str) -> tuple[tuple[int, int] | None, tuple[int, int] | None, bool]:
    raw = str(dates or "")
    low = raw.lower()
    open_ended = any(w in low for w in ("present", "current", "now", "ongoing"))
    parts = [p for p in re.split(r"\s*[-–—]\s*|\s+to\s+", raw) if p.strip()]
    if not parts:
        return None, None, open_ended
    start = _parse_month_year(parts[0])
    end = None if open_ended else (_parse_month_year(parts[-1]) if len(parts) > 1 else start)
    return start, end, open_ended


def _gap_flags(base: dict) -> list[str]:
    """Advisory employment-gap warnings from the BASE résumé's own date ranges.

    ~48% of employers screen on gaps longer than six months, so the user is told
    about one. Nothing in this pipeline ever rewrites a date to hide it.
    """
    entries = []
    for e in (base.get("work_experience") or base.get("experience") or []):
        if not isinstance(e, dict):
            continue
        start, end, open_ended = _date_range(e.get("dates", ""))
        if start is None:
            continue
        label = str(e.get("organization") or e.get("company") or e.get("title") or "?")
        entries.append((start, end, open_ended, label))
    entries.sort(key=lambda t: t[0])

    flags: list[str] = []
    running_end: tuple[int, int] | None = None
    prev_label = ""
    for start, end, open_ended, label in entries:
        if running_end is not None:
            months = (start[0] - running_end[0]) * 12 + (start[1] - running_end[1])
            if months > 6:
                flags.append(f"gap:>6mo between {prev_label} and {label}")
        if open_ended:
            running_end, prev_label = None, label
            continue
        if end is not None and (running_end is None or end > running_end):
            running_end, prev_label = end, label
    return flags


def coverage(analysis: "JDAnalysis", resume_data: Any, *,
             max_repetition: int = 3, base: dict | None = None,
             base_resume_path: str | Path | None = None) -> CoverageReport:
    """How much of THIS job description the résumé honestly covers.

    Not an ATS score — no ATS computes one. Each JD term contributes its weight
    at most once however often it appears; repetition past ``max_repetition``
    lands in ``overused`` and costs points upstream. A requirement counts as
    *covered* only when at least one matched term appears in a résumé BULLET:
    naming a technology in a skills grid is a claim, a bullet is evidence, and
    that difference is the whole of the "context, not a keyword wall" rule.
    """
    zones = _build_zones(resume_data)
    kw_cov = KeywordCoverage()

    all_text = " ".join(t for _l, t in zones.bullets + zones.skills + zones.header)
    all_hay = normalize(all_text)

    for kw in analysis.keywords:
        kw_cov.total_weight += kw.weight
        zone, _label = _locate(kw.term, zones)
        if zone is None:
            if kw.n > 1 and _spans_lines(kw.term, zones):
                kw_cov.phrase_breaks.append(kw.term)
            kw_cov.missing.append(kw)
            continue
        kw_cov.covered.append(kw)
        kw_cov.zones[kw.term] = zone
        kw_cov.covered_weight += kw.weight
        forms = _attesting_sources(kw.term) or {kw.term}
        n_occ = max(_count_phrase(all_hay, f) for f in forms)
        if n_occ > max_repetition:
            kw_cov.overused.append((kw.term, n_occ))

    kw_cov.covered_weight = round(kw_cov.covered_weight, 6)
    kw_cov.total_weight = round(kw_cov.total_weight, 6)
    kw_cov.fraction = round(kw_cov.covered_weight / kw_cov.total_weight, 6) \
        if kw_cov.total_weight else 0.0
    kw_cov.overused.sort()
    kw_cov.phrase_breaks.sort()

    req_cov: list[RequirementCoverage] = []
    w_cov = w_par = w_all = 0.0
    for req in analysis.requirements:
        hits: list[str] = []
        where: list[str] = []
        zones_hit: list[str] = []
        for term in req.terms:
            zone, label = _locate(term, zones)
            if zone is not None:
                hits.append(term)
                zones_hit.append(zone)
                if label and label not in where:
                    where.append(label)
        need = max(1, math.ceil(0.5 * len(req.terms))) if req.terms else 1
        if hits and len(hits) >= need and "bullet" in zones_hit:
            status = "covered"
        elif hits:
            status = "partial"
        else:
            status = "missing"
        req_cov.append(RequirementCoverage(requirement=req, status=status,
                                           matched_terms=hits, matched_in=where))
        w_all += req.weight
        if status == "covered":
            w_cov += req.weight
        elif status == "partial":
            w_par += req.weight
    requirement_fraction = ((w_cov + 0.5 * w_par) / w_all) if w_all else 0.0

    title_toks = set(content_tokens(analysis.job_title or ""))
    resume_titles = " ".join(t for label, t in zones.header if label.endswith(".title"))
    resume_title_toks = set(content_tokens(resume_titles))
    title_alignment = (len(title_toks & resume_title_toks) / len(title_toks)) \
        if title_toks else 0.0

    bullets = [t for _l, t in zones.bullets]
    n_quant = n_front = 0
    for b in bullets:
        m = QUANT_RE.search(b)
        if not m:
            continue
        n_quant += 1
        if len(tokens(b[:m.start()])) < 12:
            n_front += 1
    quantified_fraction = min(1.0, (n_quant + 0.25 * n_front) / max(1, len(bullets)))

    skills_tok = len(tokens(" ".join(t for _l, t in zones.skills)))
    body_tok = skills_tok + len(tokens(" ".join(bullets)))
    keyword_wall = (skills_tok / max(1, body_tok)) > 0.35

    # Format-integrity notes. These are guarantees of _create_resume_docx, not
    # warnings: single-column, no tables, no text boxes, standard section
    # headings. contact_in_body is likewise always satisfied, so it is asserted
    # by the renderer rather than reported here.
    flags = ["docx:no_tables", "docx:no_textboxes", "docx:standard_headings"]
    if isinstance(resume_data, dict):
        for kind in ("work_experience", "experience"):
            for e in resume_data.get(kind) or []:
                if isinstance(e, dict) and e.get("dates") \
                        and not _YEAR_RE.search(str(e["dates"])):
                    label = e.get("organization") or e.get("company") \
                        or e.get("title") or "?"
                    flags.append(f"dates:unparseable:{label}")
    base_data = base if base is not None else load_base_resume(base_resume_path)
    flags.extend(_gap_flags(base_data or {}))

    return CoverageReport(
        keywords=kw_cov, requirements=req_cov,
        requirement_fraction=round(requirement_fraction, 6),
        title_alignment=round(title_alignment, 6),
        quantified_fraction=round(quantified_fraction, 6),
        keyword_wall=keyword_wall, flags=flags)


