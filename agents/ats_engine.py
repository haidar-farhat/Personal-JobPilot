def _build_alias_table(groups: list[set[str]]) -> dict[str, frozenset[str]]:
    """Union-find merge, so two seed groups sharing a member become one class."""
    parent: dict[str, str] = {}

    def find(x: str) -> str:
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(a: str, b: str) -> None:
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[max(ra, rb)] = min(ra, rb)

    for grp in groups:
        members = [normalize(m) for m in sorted(grp) if normalize(m)]
        for m in members[1:]:
            union(members[0], m)

    classes: dict[str, set[str]] = {}
    for term in list(parent):
        classes.setdefault(find(term), set()).add(term)
    return {t: frozenset(members) for members in classes.values() for t in members}


