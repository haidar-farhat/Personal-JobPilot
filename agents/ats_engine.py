def _requirement_units(section_text: str) -> list[str]:
    units: list[str] = []
    for line in section_text.splitlines():
        line = line.strip()
        if not line:
            continue
        pieces = [line]
        if len(tokens(line)) > 45:
            pieces = [p for p in _SENTENCE_SPLIT_RE.split(line) if p.strip()]
        for piece in pieces:
            piece = _BULLET_GLYPH_RE.sub("", piece.strip()).strip()
            if piece:
                units.append(piece)
    return units


def _requirement_terms(kws: list[Keyword], *, max_terms: int = 5) -> tuple[str, ...]:
    """The distinct concepts one requirement line demands.

    Two adjustments to a plain "top 5 by weight". Technical terms sort first,
    because a requirement's identity is the technology it names, not the prose
    wrapped around it. And a candidate sharing any token with an already-chosen
    term is skipped, so one noun phrase cannot occupy all five slots as five
    overlapping windows of itself — that would push ``need`` to 3 and make the
    requirement unmatchable by any résumé that had not copied the posting's
    sentence structure verbatim.
    """
    if not kws:
        return ()
    floor = 0.15 * max(k.weight for k in kws)
    chosen: list[str] = []
    used: set[str] = set()
    for kw in sorted(kws, key=lambda k: (not k.is_technical, -k.weight, k.term)):
        if kw.weight < floor:
            continue
        parts = set(kw.term.split())
        if parts & used:
            continue
        chosen.append(kw.term)
        used |= parts
        if len(chosen) >= max_terms:
            break
    return tuple(chosen)


def _classify_kind(unit: str, section: str) -> str:
    low = unit.translate(_PUNCT_FOLD).lower()
    if any(cue in low for cue in NICE_CUES):
        return "nice"
    if any(cue in low for cue in MUST_CUES):
        return "must"
    if section == "nice_to_have":
        return "nice"
    if section == "requirements":
        return "must"
    return "nice"


def _dedupe_requirements(reqs: list[tuple[float, int, Requirement]]
                         ) -> list[tuple[float, int, Requirement]]:
    kept: list[tuple[float, int, Requirement]] = []
    seen_text: dict[str, int] = {}
    for item in reqs:
        weight, _order, req = item
        norm_text = normalize(req.text)
        if norm_text in seen_text:
            idx = seen_text[norm_text]
            if weight > kept[idx][0]:
                kept[idx] = item
            continue
        terms = set(req.terms)
        merged = False
        for idx, (kw, _ko, kreq) in enumerate(kept):
            other = set(kreq.terms)
            if not terms or not other:
                continue
            overlap = len(terms & other) / max(1, min(len(terms), len(other)))
            if overlap >= 0.80:
                if weight > kw:
                    kept[idx] = item
                merged = True
                break
        if merged:
            continue
        seen_text[norm_text] = len(kept)
        kept.append(item)
    return kept


def extract_requirements(jd: str, *, max_requirements: int = 24,
                         base_resume_path: str | Path | None = None) -> list[Requirement]:
    """One `Requirement` per genuine JD demand, weighted by section and modality.

    An explicit in-text cue always beats the section default, and a NICE cue wins
    a tie: over-calling something a must-have inflates the denominator of
    ``requirement_fraction`` and makes an honest résumé look worse than it is. A
    unit yielding no salient terms is prose, not a requirement, and is discarded
    rather than scored against.
    """
    sections = split_jd_sections(jd or "")
    if not any(k not in ("benefits", "about") for k in sections):
        # Postings whose only headings are "About Our Company" / "About the
        # Position" carry their real demands as prose underneath. Dropping
        # those sections wholesale would discard the entire posting and push a
        # perfectly analysable JD onto the title-only path, so it is re-read
        # unsegmented at the `unknown` weight instead.
        sections = {"unknown": jd or ""}
    reqs: list[tuple[float, int, Requirement]] = []
    order = 0

    for section, text in sections.items():
        if section in ("benefits", "about"):
            continue
        sw = SECTION_WEIGHTS.get(section, SECTION_WEIGHTS["unknown"])
        for unit in _requirement_units(text):
            toks = tokens(unit)
            if not (4 <= len(toks) <= 60):
                continue
            if not any(t not in STOPWORDS and t not in LOW_SIGNAL for t in toks):
                continue
            low = unit.lower()
            if any(bp in low for bp in BOILERPLATE_PHRASES):
                continue

            kind = _classify_kind(unit, section)
            kws = extract_keywords({section: unit}, top_n=12,
                                   base_resume_path=base_resume_path)
            if not kws:
                continue
            terms = _requirement_terms(kws)
            if not terms:
                continue

            order += 1
            weight = round(sw * (MUST_WEIGHT if kind == "must" else NICE_WEIGHT), 6)
            reqs.append((weight, order, Requirement(
                id="", text=unit[:220].strip(), kind=kind, section=section,
                weight=weight, terms=terms)))

    kept = _dedupe_requirements(reqs)
    kept.sort(key=lambda r: (-r[0], r[1]))
    return [Requirement(id=f"R{i}", text=r.text, kind=r.kind, section=r.section,
                        weight=r.weight, terms=r.terms)
            for i, (_w, _o, r) in enumerate(kept[:max_requirements], start=1)]


