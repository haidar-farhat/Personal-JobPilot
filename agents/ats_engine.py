@dataclass
class JDAnalysis:
    job_title: str
    company: str
    sections: dict[str, str]
    requirements: list[Requirement]
    keywords: list[Keyword]
    hints: list[ExpansionHint]
    jd_hash: str


def _requirements_from_title(title: str, seeds: Sequence[str]) -> list[Requirement]:
    """Degenerate fallback for a posting with no usable description.

    51% of scanned rows carry a description under 50 characters, so this path is
    load-bearing rather than exotic. Everything it emits is labelled
    ``section="unknown"`` so the UI can say "inferred from title" instead of
    implying the posting said any of it.
    """
    sw = SECTION_WEIGHTS["unknown"]
    weight = round(sw * MUST_WEIGHT, 6)
    out: list[Requirement] = []
    seen: set[str] = set()

    title_terms = tuple(t for t in content_tokens(title or "") if t not in LOW_SIGNAL)[:4]
    if title_terms:
        out.append(Requirement(id="R1",
                               text=f"Work matching the title: {title}".strip()[:220],
                               kind="must", section="unknown",
                               weight=weight, terms=title_terms))
        seen.update(title_terms)

    for seed in seeds or []:
        term = normalize(seed)
        if not term or term in seen:
            continue
        seen.add(term)
        out.append(Requirement(id=f"R{len(out) + 1}",
                               text=f"Experience with {seed}"[:220],
                               kind="must", section="unknown",
                               weight=weight, terms=(term,)))
    return out


def _llm_requirement_seed(job: Any) -> list[str]:
    """ONE optional model call, used only when the posting is title-only.

    Its output is a SEED LIST and nothing else: every returned term still passes
    the same shape gate as a term read out of a real posting, enters at half the
    median weight, and every count and score downstream is computed in Python. A
    failure here is not an error — the title-only path simply stays title-only.
    """
    try:
        from utils.ollama_client import generate_json
        title = getattr(job, "title", "") or ""
        company = getattr(job, "company", "") or ""
        prompt = (f"List the 10 skills a job posting for '{title}' at '{company}' "
                  f"would most likely require. Return JSON only: "
                  f"{{\"terms\": [\"...\"]}}")
        result = generate_json(prompt, system_prompt=(
            "You list likely job-posting skill terms. Respond with JSON only.")) or {}
        terms = result.get("terms") or []
        return [str(t) for t in terms if isinstance(t, (str, int, float))][:10]
    except Exception as exc:
        logger.warning("[ats_engine] LLM requirement seed unavailable: %s", exc)
        return []


def analyze_jd(job: Any, job_score: Any = None, *, jd_max_chars: int = 12000,
               use_llm: bool = False,
               base_resume_path: str | Path | None = None) -> JDAnalysis:
    """The single entry point tailor.py and resume_optimizer.py call.

    Deterministic unless ``use_llm=True`` AND the posting is too short to
    analyse; even then the model only contributes candidate terms, which are
    re-verified here by the same gate as any JD-sourced term.
    """
    jd = (getattr(job, "description", None) or "")[:jd_max_chars]
    title = getattr(job, "title", None) or ""
    company = getattr(job, "company", None) or ""

    sections = split_jd_sections(jd)
    seeds: list[str] = []
    if job_score is not None:
        raw_seeds = getattr(job_score, "ats_keywords", None) or []
        if isinstance(raw_seeds, (list, tuple)):
            seeds = [str(s) for s in raw_seeds]

    if use_llm and len(content_tokens(jd)) < 40:
        seeds = seeds + _llm_requirement_seed(job)

    keywords = extract_keywords(sections, top_n=MAX_KEYWORDS, seed_terms=seeds,
                                base_resume_path=base_resume_path)
    requirements = extract_requirements(jd, base_resume_path=base_resume_path)
    if not requirements:
        requirements = _requirements_from_title(title, seeds)
    hints = expansion_hints(keywords, attested_vocabulary(base_resume_path))

    jd_hash = hashlib.sha1(normalize(jd)[:200000].encode("utf-8")).hexdigest()
    return JDAnalysis(job_title=title, company=company, sections=sections,
                      requirements=requirements, keywords=keywords, hints=hints,
                      jd_hash=jd_hash)


