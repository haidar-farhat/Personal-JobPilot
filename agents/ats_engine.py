def _heading_key(line: str) -> str | None:
    """Section key for a heading line, or None when the line is content."""
    stripped = line.strip().lstrip("#*-•●").strip()
    ends_colon = stripped.endswith(":")
    stripped = stripped.rstrip(":").strip()
    if not stripped:
        return None
    n_toks = len(stripped.split())
    low = stripped.translate(_PUNCT_FOLD).lower()

    if stripped[-1] in ".,;!?":
        # A heading does not end in sentence punctuation. Without this the
        # extremely common bullet opener "Must have ..." matches the
        # `must[- ]haves?` heading alternative and swallows the line.
        return None
    if n_toks <= 8:
        for rx, key in SECTION_HEADINGS:
            m = rx.search(low)
            # The cue has to BE the heading, not merely start the line: a
            # two-word cue in front of a full sentence is a bullet.
            if m and (n_toks <= 3 or m.end() >= 0.5 * len(low)):
                return key
    if ends_colon and n_toks <= 6:
        words = [w for w in stripped.split() if any(c.isalpha() for c in w)]
        title_case = bool(words) and all(w[0].isupper() for w in words)
        all_caps = bool(words) and all(w.isupper() for w in words)
        if title_case or all_caps:
            for rx, key in SECTION_HEADINGS:
                if rx.search(low):
                    return key
            return "unknown"
    return None


def _strip_boilerplate(text: str) -> str:
    low = text.lower()
    for bp in BOILERPLATE_PHRASES:
        low = low.replace(bp, " ")
    return low


def split_jd_sections(jd: str) -> dict[str, str]:
    """Split a posting into weighted sections. Never raises.

    Heading detection is deliberately conservative. A mis-fired heading moves a
    whole block into the wrong weight class, which is worse than leaving the
    posting unsegmented at the 0.60 ``unknown`` weight — under-segmenting costs
    resolution, mis-segmenting costs correctness.
    """
    jd = jd or ""
    if not jd.strip():
        return {"unknown": ""}

    blocks: list[tuple[str, list[str]]] = [("unknown", [])]
    found_heading = False
    for raw in jd.splitlines():
        if not raw.strip():
            blocks[-1][1].append("")
            continue
        key = _heading_key(raw)
        if key is not None:
            found_heading = True
            blocks.append((key, []))
        else:
            blocks[-1][1].append(raw.rstrip())

    if not found_heading:
        return {"unknown": jd}

    merged: dict[str, list[str]] = {}
    for key, lines in blocks:
        text = "\n".join(lines).strip()
        if text:
            merged.setdefault(key, []).append(text)

    out: dict[str, str] = {}
    for key, chunks in merged.items():
        text = "\n".join(chunks).strip()
        if len(content_tokens(_strip_boilerplate(text))) < 3:
            continue
        out[key] = text
    return out or {"unknown": jd}


