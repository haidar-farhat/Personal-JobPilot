ACRONYM_PAIRS: dict[str, str] = {
    "nlp": "natural language processing", "cv": "computer vision",
    "rag": "retrieval augmented generation", "ml": "machine learning",
    "llm": "large language model", "api": "application programming interface",
    "ci/cd": "continuous integration and delivery",
    "ocr": "optical character recognition",
    "gis": "geographic information systems", "sql": "structured query language",
}
_ACRONYM_BY_EXPANSION = {v: k for k, v in ACRONYM_PAIRS.items()}


def expansion_hints(keywords: list[Keyword],
                    attested: frozenset[str]) -> list[ExpansionHint]:
    """Recommend the single "expansion (ACRONYM)" mention for attested pairs.

    Roughly four extra characters, and it satisfies both layers at once: the
    lexical layer (Boolean search — no stemming, no aliasing) sees both surface
    forms, and a parser's taxonomy layer sees the canonical expansion. A hint is
    never emitted for a pair the candidate cannot attest, because recommending a
    term the résumé cannot support is the fabrication path this design exists to
    close.
    """
    hints: list[ExpansionHint] = []
    seen: set[str] = set()
    for kw in keywords:
        term = kw.term
        if term in ACRONYM_PAIRS:
            acronym, expansion = term, ACRONYM_PAIRS[term]
        elif term in _ACRONYM_BY_EXPANSION:
            acronym, expansion = _ACRONYM_BY_EXPANSION[term], term
        else:
            continue
        other = expansion if term == acronym else acronym
        if other not in attested and term not in attested:
            continue
        if acronym in seen:
            continue
        seen.add(acronym)
        hints.append(ExpansionHint(jd_form=term, other_form=other,
                                   recommended=f"{expansion} ({acronym.upper()})"))
    return hints


