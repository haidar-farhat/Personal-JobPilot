def _resolve_base_path(path: str | Path | None) -> str:
    return str(path) if path else str(BASE_RESUME_PATH)


@functools.lru_cache(maxsize=8)
def _load_base_resume_cached(resolved: str) -> dict:
    try:
        import yaml
        with open(resolved, "r", encoding="utf-8") as fh:
            data = yaml.safe_load(fh) or {}
        return data if isinstance(data, dict) else {}
    except FileNotFoundError:
        logger.warning("[ats_engine] base résumé not found at %s — running with an "
                       "alias-only lexicon; coverage will under-report", resolved)
        return {}
    except Exception as exc:               # malformed YAML must not kill scoring
        logger.warning("[ats_engine] could not read base résumé %s: %s", resolved, exc)
        return {}


def load_base_resume(path: str | Path | None = None) -> dict:
    """`config/base_resume.yaml` as a dict. Cached; pass a path in tests.

    Lazy rather than module-level on purpose: importing this module must not
    touch the filesystem, and a missing (gitignored) résumé has to degrade to an
    alias-only lexicon instead of raising at import time.
    """
    return _load_base_resume_cached(_resolve_base_path(path))


def _iter_strings(node: Any) -> Iterable[str]:
    if isinstance(node, str):
        yield node
    elif isinstance(node, dict):
        for k, v in node.items():
            if isinstance(k, str):
                yield k
            yield from _iter_strings(v)
    elif isinstance(node, (list, tuple)):
        for v in node:
            yield from _iter_strings(v)


def _split_items(value: Any) -> list[str]:
    """Skill values are either a YAML list or a comma/·-separated string."""
    if isinstance(value, (list, tuple)):
        return [str(v).strip() for v in value if str(v).strip()]
    if isinstance(value, str):
        return [p.strip() for p in re.split(r"[,;·|]", value) if p.strip()]
    return []


@functools.lru_cache(maxsize=8)
def _tech_lexicon_cached(resolved: str) -> frozenset[str]:
    base = _load_base_resume_cached(resolved)
    lex: set[str] = set()

    def add(raw: str) -> None:
        n = normalize(raw)
        if n and len(n) <= 60:
            lex.add(n)
            flat = _flatten(n)
            if flat != n:
                lex.add(flat)

    skills = base.get("skills") or base.get("technical_skills") or {}
    if isinstance(skills, dict):
        for cat, val in skills.items():
            add(str(cat))
            for item in _split_items(val):
                add(item)
    elif isinstance(skills, (list, tuple)):
        for item in skills:
            add(str(item))

    for key in ("project_experience", "projects", "work_experience", "experience"):
        for entry in base.get(key) or []:
            if not isinstance(entry, dict):
                continue
            for stack_key in ("tech_stack", "stack", "technologies"):
                for item in _split_items(entry.get(stack_key)):
                    add(item)

    for cert in base.get("certifications") or []:
        add(str(cert.get("name", "")) if isinstance(cert, dict) else str(cert))

    lex.update(ALIAS_TABLE)
    lex.update(TERM_IMPLIES)
    for implied in TERM_IMPLIES.values():
        lex.update(implied)
    lex.discard("")
    return frozenset(lex)


def tech_lexicon(path: str | Path | None = None) -> frozenset[str]:
    """The "this n-gram is technical" gate — never a coverage gate.

    A JD term absent from this set is still scored; the lexicon only decides
    whether a bare unigram is admissible as a keyword at all.
    """
    return _tech_lexicon_cached(_resolve_base_path(path))


def _attesting_sources(term: str) -> frozenset[str]:
    """Every surface form whose presence honestly attests `term`.

    Symmetric group members both ways, plus any ``x`` with ``x -> term`` (and
    that ``x``'s own synonyms). Never the reverse of an entailment: ``sql`` in a
    JD is not evidence of ``mysql`` on a résumé.
    """
    t = normalize(term)
    if not t:
        return frozenset()
    forms = set(ALIAS_TABLE.get(t, frozenset({t}))) | {t}
    for src, implied in TERM_IMPLIES.items():
        if forms & set(implied):
            forms |= set(ALIAS_TABLE.get(src, frozenset({src}))) | {src}
    return frozenset(forms)


def _implied_by(term: str) -> frozenset[str]:
    """Forward closure: everything `term` honestly attests, including itself."""
    t = normalize(term)
    if not t:
        return frozenset()
    seen = set(ALIAS_TABLE.get(t, frozenset({t}))) | {t}
    for _ in range(3):                    # fixed point; chains are 2 deep at most
        grown = set(seen)
        for f in list(seen):
            grown |= set(TERM_IMPLIES.get(f, ()))
        for f in list(grown):
            grown |= set(ALIAS_TABLE.get(f, ()))
        if grown == seen:
            break
        seen = grown
    return frozenset(seen)


@functools.lru_cache(maxsize=8)
def _attested_vocabulary_cached(resolved: str) -> frozenset[str]:
    base = _load_base_resume_cached(resolved)
    vocab: set[str] = set()
    for text in _iter_strings(base):
        for gram, _idx in ngrams(tokens(text), 3):
            vocab.add(gram)
            flat = _flatten(gram)
            if flat != gram:
                vocab.add(flat)
    closed = set(vocab)
    for term in vocab:
        closed |= set(_implied_by(term))
    closed.discard("")
    return frozenset(closed)


def attested_vocabulary(path: str | Path | None = None) -> frozenset[str]:
    """Every 1..3-gram in the base résumé, closed under alias + entailment.

    This is the honesty boundary: a term outside this set cannot be written into
    a résumé without inventing experience, so the feedback layer must never
    recommend one.
    """
    return _attested_vocabulary_cached(_resolve_base_path(path))


def reset_caches() -> None:
    """Drop every cached filesystem read. For tests that swap the résumé path."""
    _load_base_resume_cached.cache_clear()
    _tech_lexicon_cached.cache_clear()
    _attested_vocabulary_cached.cache_clear()
    _term_regex.cache_clear()


