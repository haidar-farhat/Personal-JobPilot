def normalize(s: str) -> str:
    """Lowercase, fold unicode dashes/quotes, keep only `_KEEP`, collapse spaces.

    Technical punctuation is deliberately preserved: ``c++``, ``c#``, ``ci/cd``,
    ``node.js`` and ``scikit-learn`` survive intact, because those are the exact
    surface forms an unstemmed Boolean ATS search looks for.
    """
    if not s:
        return ""
    folded = str(s).translate(_PUNCT_FOLD).lower().replace("'", "")
    kept = "".join(c if c in _KEEP_SET else " " for c in folded)
    out = []
    for tok in kept.split():
        # Sentence punctuation that _KEEP lets through would otherwise weld
        # itself to the word ("awry." != "awry") and break every later phrase
        # comparison. Stripping it only at the edges leaves node.js, ci/cd,
        # scikit-learn, c++ and 100+ intact.
        tok = tok.strip("./-_")
        if tok:
            out.append(tok)
    return " ".join(out)


def _flatten(norm: str) -> str:
    """Hyphen-insensitive view of a normalised string.

    ``cross-functional`` and ``cross functional`` are one term to a human reader
    and to every ATS search box; matching against both views stops a hyphen from
    silently costing coverage without doubling every table entry.
    """
    return norm.replace("-", " ") if "-" in norm else norm


def tokens(s: str) -> list[str]:
    """Normalised whitespace tokens; hyphenated compounds kept whole AND split.

    A compound is emitted whole and, when every side is an alphabetic run longer
    than two characters, its parts follow it. So ``scikit-learn`` survives whole
    (a library name an ATS matches literally) while ``cross-functional`` also
    yields ``cross``/``functional``. The redundant grams this creates are dropped
    by the contiguity check in :func:`extract_keywords`, which requires every
    accepted n-gram to occur verbatim in the source text.
    """
    out: list[str] = []
    for tok in normalize(s).split(" "):
        if not tok:
            continue
        out.append(tok)
        if "-" in tok:
            parts = [p for p in tok.split("-") if p]
            if len(parts) >= 2 and all(len(p) > 2 and p.isalpha() for p in parts):
                out.extend(parts)
    return out


def _suffix_strip(t: str) -> str:
    if t.endswith("ies") and len(t) > 4:
        return t[:-3] + "y"
    for suf in ("sses", "shes", "ches", "xes"):
        if t.endswith(suf) and len(t) > len(suf):
            return t[:-2]
    if t.endswith("s") and len(t) > 3 and not t.endswith(("ss", "us", "is")):
        return t[:-1]
    return t


def content_tokens(s: str) -> list[str]:
    """`tokens()` minus stopwords, naively de-pluralised.

    Similarity only — never rendered and never used as an output surface form,
    because a suffix strip this crude is wrong often enough that showing its
    result to a user would be worse than useless.
    """
    return [_suffix_strip(t) for t in tokens(s) if t not in STOPWORDS]


def ngrams(toks: list[str], n_max: int = 3) -> list[tuple[str, int]]:
    """All contiguous 1..n_max grams as ``(gram, start_index)``.

    A gram whose first or last token is a stopword is discarded: "of the data"
    and "data and" are sentence glue, not terms.
    """
    out: list[tuple[str, int]] = []
    n_toks = len(toks)
    for n in range(1, max(1, n_max) + 1):
        for i in range(n_toks - n + 1):
            gram = toks[i:i + n]
            if gram[0] in STOPWORDS or gram[-1] in STOPWORDS:
                continue
            out.append((" ".join(gram), i))
    return out


def contains_phrase(haystack_norm: str, term: str) -> bool:
    """Word-boundary containment of the *contiguous* normalised term.

    This is the exact-phrase-integrity check. `normalize()` has already collapsed
    newlines to spaces, so a caller that wants to detect a genuine phrase break
    must pass per-line text — :func:`coverage` does exactly that for every
    multi-word term.
    """
    t = normalize(term)
    if not t or not haystack_norm:
        return False
    hays = {f" {haystack_norm} "}
    flat_h = _flatten(haystack_norm)
    if flat_h != haystack_norm:
        hays.add(f" {flat_h} ")
    needles = {f" {t} "}
    flat_t = _flatten(t)
    if flat_t != t:
        needles.add(f" {flat_t} ")
    return any(n in h for n in needles for h in hays)


def _count_phrase(haystack_norm: str, term: str) -> int:
    """Overlap-safe occurrence count of a normalised term in normalised text."""
    t = _flatten(normalize(term))
    if not t or not haystack_norm:
        return 0
    hay = f" {_flatten(haystack_norm)} "
    needle = f" {t} "
    count, pos = 0, 0
    while True:
        idx = hay.find(needle, pos)
        if idx < 0:
            return count
        count += 1
        pos = idx + 1


@functools.lru_cache(maxsize=8192)
def _term_regex(term: str) -> re.Pattern[str]:
    """Case-insensitive pattern matching a normalised term in ORIGINAL text."""
    atoms = [a for a in re.split(r"[\s\-]+", term) if a]
    body = r"[\s\-]+".join(re.escape(a) for a in atoms) or re.escape(term)
    return re.compile(rf"(?<![0-9A-Za-z]){body}(?![0-9A-Za-z])", re.I)


def _first_occurrence(term: str, original: str) -> str | None:
    if not term or not original:
        return None
    m = _term_regex(term).search(original)
    return m.group(0) if m else None


def _is_capitalised_in(term: str, original: str) -> bool:
    """Is the term's first occurrence written as a proper noun?

    For a multi-word gram this demands Title Case across the whole phrase, not
    just a capital on the first word. "Machine Learning" and "Mixed Reality" are
    product/domain names a posting deliberately capitalises; "Python experience"
    is one capitalised term followed by ordinary prose, and admitting it would
    let every sentence-initial technical word drag its neighbours in.
    """
    surface = _first_occurrence(term, original)
    if not surface:
        return False
    words = [w for w in re.split(r"[^0-9A-Za-z]+", surface) if any(c.isalpha() for c in w)]
    if not words:
        return False
    return all(next(c for c in w if c.isalpha()).isupper() for w in words)


